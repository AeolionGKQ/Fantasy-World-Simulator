def _rank_rows(titles, theoretical_below=1):
    rows = []
    for rank in range(1, 11):
        warning = None
        if rank < theoretical_below:
            warning = "精灵出生时就有三阶的魔力基础，一阶和二阶只是理论分类。选择这两阶时，请在角色设定中说明角色为何还不能完全发挥战斗能力。"
        elif rank >= 7:
            warning = _HIGH_RANK_WARNING
        rows.append({"rank": rank, "display_rank": f"{_CHINESE_RANKS[rank - 1]}阶",
                     "name": f"{_CHINESE_RANKS[rank - 1]}阶", "title": titles[rank - 1],
                     "base_power": POWER_BY_RANK[rank], "description": _RANK_DESCRIPTIONS[rank], "disabled": False,
                     "warning": warning})
    return rows


